/**
 * Разобрать вставленный/загруженный список марок в массив кодов.
 *
 * Разделители — только перевод строки и табуляция (по коду в строке). Запятую и
 * пробел разделителями НЕ считаем: серийный номер КМ (AI 21) — это подмножество
 * 82-символьного GS1-набора, куда входят «,», «(», «)», «&», «+», «.», «=», «_».
 * Резать по запятой рвало реальные коды с запятой в серии на обрезок + сироту-
 * фрагмент (проверено на проде 2026-08-25: серия «tXz,…» → «(21)tXz» + «xak»),
 * после чего ЧЗ отвечал 404 «КМ/КИ не найден». Пустые строки отбрасываем, дубли
 * схлопываем с сохранением порядка.
 */
export function parseCodeList(text: string): string[] {
  const seen = new Set<string>()
  const out: string[] = []
  for (const part of text.split(/[\r\n\t]+/)) {
    const code = part.trim()
    if (!code || seen.has(code)) continue
    seen.add(code)
    out.push(code)
  }
  return out
}
